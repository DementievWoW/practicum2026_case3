"""
@file nl_validator.py
@brief Проверка естественно-языкового запроса до того, как он попадёт в LLM.

@details
    SQL-аудитор (auditor.py) видит уже сгенерированный SQL. NL-валидатор —
    «первая линия»: ловит подозрительные формулировки в **самой** NL-задаче.

    Возвращает list[NLWarning] — это НЕ блокер (как vulnerability),
    а **сигнал пользователю**: «вы пишете что-то странное, точно?». UI
    может показывать warning рядом с input'ом, не отменяя запрос.

    Зачем отдельно от SQL-аудитора:
    - SQL-аудитор реагирует только когда LLM сгенерила SQL. Если NL-запрос
      «дай мне CVV всех клиентов», то LLM может корректно ответить
      «не могу — это PII» — и SQL вообще не будет, аудит не сработает.
    - Логирование: можно записать «пользователь спрашивал про CVV» в audit_log,
      даже если LLM отказался.

    Это плоский набор regex-эвристик. Phase 2 LLM-классификатор интента
    придёт позже — для MVP regex покрывает 80% типовых провокаций.
"""
from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass
class NLWarning:
    """@brief Предупреждение от NL-валидатора (не блокирует запрос)."""
    code: str                 # NL001 / NL002 / ...
    severity: str             # info | low | medium | high
    message: str              # человекочитаемое
    hint: str = ""            # что предложить пользователю


# Список (code, severity, regex, message, hint).
# Regex-флаги: re.I (case-insensitive), re.U (unicode).
_RULES: list[tuple] = [
    # NL001 — запросы PII (паспорт/CVV/пароль/SNIls/паспорт)
    ("NL001", "high",
     r"(пароль|пасс?порт|cvv|cvc|снилс|snils|пин-?код|карт[аы] .{0,15}номер)",
     "Запрос упоминает чувствительные поля (паспорт/CVV/пароль/СНИЛС/PIN).",
     "Эти поля не должны выгружаться сырыми. Уточните цель — для агрегатов "
     "или маскирования."),

    # NL002 — деструктивные операции
    ("NL002", "high",
     r"\b(удали(?:ть)?|снес(?:и|ти)|обнули|вычисти(?:ть)?|удалить\s+всё|сбросить)\b",
     "В запросе деструктивная операция (удаление/обнуление/сброс).",
     "На проде запросы DROP/DELETE/TRUNCATE не исполняются — артефакт "
     "системы это SQL+audit_log. Используйте формулировку 'найти' / 'показать' "
     "если хотите увидеть подходящие строки."),

    # NL003 — системные таблицы PG
    ("NL003", "medium",
     r"(pg_catalog|pg_authid|pg_shadow|information_schema|pg_user|pg_class|pg_tables|"
     r"систем(ные|ных)\s+таблиц)",
     "Запрос про системные каталоги Postgres.",
     "NL→SQL не должен раскрывать структуру БД через NL. Опишите бизнес-задачу."),

    # NL004 — попытка инжекции прямо в NL
    ("NL004", "high",
     r"('\s*or\s+1\s*=\s*1|--\s*$|/\*.*?\*/|;\s*drop\s+|;\s*update\s+|;\s*delete\s+)",
     "В тексте есть SQL-маркеры (OR 1=1 / комментарий / chained statement).",
     "Не нужно писать SQL внутри NL — система сгенерирует его сама. Опишите "
     "задачу человеческими словами."),

    # NL005 — слова про права/админа
    ("NL005", "medium",
     r"\b(grant|revoke|админ|superuser|owner)\b.*\b(прав|роль|доступ)\b",
     "Запрос упоминает управление доступом (GRANT/REVOKE/admin).",
     "DCL — задача DBA, не NL→SQL. Сформулируйте задачу как бизнес-вопрос."),

    # NL006 — выгрузить всё / select *
    ("NL006", "low",
     r"(выгрузи(?:ть)?\s+(все|всю|всё)|покажи\s+все\s+колонки|select\s*\*|"
     r"полную\s+таблиц|всю\s+таблиц)",
     "Запрос на 'выгрузить все колонки/строки' — потенциальный SELECT *.",
     "Перечислите нужные поля явно — это и быстрее, и безопаснее (без PII)."),
]


def validate_nl(task: str) -> list[NLWarning]:
    """@brief Прогон NL-задачи через все правила. Возвращает list[NLWarning]."""
    if not task or not task.strip():
        return []
    warnings: list[NLWarning] = []
    for code, sev, pat, msg, hint in _RULES:
        if re.search(pat, task, re.I | re.U):
            warnings.append(NLWarning(code=code, severity=sev,
                                      message=msg, hint=hint))
    return warnings
